import ollama

def get_answer(json_path: str) -> str:
    with open(json_path, "r", encoding="utf-8") as f:
        json_str = f.read()

    response = ollama.chat(
        model="mistral:7b",
        messages=[
            {"role": "system", "content": "Отвечай только на русском языке."},
            {
                "role": "user",
                "content": (
                    "Проанализируй приложенные данные. Это данные с датчиков различных гидроагрегатов\n"
                    "Данные содержат информацию о датчиках, времени начала и времени окончания аномалии.\n\n"
                    f"```json\n{json_str}\n```\n\n"
                    "Напиши человеческий отчёт, в котором расскажешь про каждую аномалию каждого датчика:\n"
                    "1. Предположишь: это поломка, гидроагрегата, датчика или ошибка в измерениях\n"
                    "2. Если это поломка гидроагрегата или датчика, то предположишь причины и\n"
                    "   дашь советы по починке. Если это ошибка в измерениях - так и напишешь.\n"
                    "Пример отчёта об одном датчике (таких должно быть ровно столько, сколько аномалий\n"
                    "на каждом датчике) (пиши эти отчёты, опираясь на время и датчик из json файла):\n"
                    "'1. **Датчик Oil_Pressure_Bar**\n "
                    "\t- Аномалия 1: Аномалия произошла в течение 7 часов с 22:13 до 22:20 (26.10.2026). Повышение давления масла\n"
                    "в системе может свидетельствовать об утечке или поломке датчика.\n"
                    "\t- Аномалия 3: Аномалия произошла в течение одной минуты с 17:04 (27.10.2026). Следствием может быть задержка или поломка датчика.\n'\n\n"
                    "Укажи более конкретные причины поломки и более конкретные рекомендации по починке"
                ),
            },
        ],
    )
    return response["message"]["content"]