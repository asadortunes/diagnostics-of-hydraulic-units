import ollama

def get_answer(json_path: str) -> str:
    with open(json_path, "r", encoding="utf-8") as f:
        json_str = f.read()

    response = ollama.chat(
        model="mistral:7b",
        messages=[
            {"role": "system", "content": "Отвечай только на русском языке."},
            {
                "role": "user",
                "content": (
                    "Ты — инженер-диагност гидроагрегатов. Ниже представлен JSON-отчёт с "
                    "найденными аномалиями телеметрии.\n"
                    "Данные содержат информацию о датчике, времени начала и времени окончания аномалии.\n\n"
                    f"```json\n{json_str}\n```\n\n"
                    "Напиши краткий человекочитаемый отчёт (5-10 предложений).\n"
                    "1. Опиши возможные поломки или неисправности, на которые указывают эти аномалии.\n"
                    "2. Дай конкретные рекомендации по обслуживанию оборудования.\n"
                    "Не выводи сырые данные, только выводы и рекомендации."
                ),
            },
        ],
    )
    return response["message"]["content"]